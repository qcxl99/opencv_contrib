"""resize with an exact-2x-upscale LINEAR specialization.

The general kernel issues 4 loads, 4 FFMAs and a rint per channel for every
output pixel. At fx == fy == 0.5 that is provably more work than the operation
needs, and the surplus is a compile-time property of the ratio rather than
anything data dependent.

With src_x = dst_x * 0.5, x1 = floor(src_x) = dst_x >> 1 and the weights are:

    dst_x even  ->  wx1 = 1.0, wx2 = 0.0      (only the left tap contributes)
    dst_x odd   ->  wx1 = 0.5, wx2 = 0.5      (mean of two adjacent taps)

and identically for rows. So the 2x2 output block generated by one source
position needs, per channel:

    (even, even)  1 tap   -- a copy
    (even, odd)   2 taps  -- horizontal mean
    (odd,  even)  2 taps  -- vertical mean
    (odd,  odd)   4 taps  -- the full bilinear mean

That averages 2.25 taps per output pixel instead of 4, and three of the four
cases drop the FFMA chain entirely. The load addresses are also shared: all
four outputs read from the same 2x2 source neighbourhood, loaded once.

Numerics are preserved exactly, not approximated. The accumulation order and
rounding of the general path are reproduced for each case:

  * weight 1.0 with the others 0.0: acc = v11, so rint(v11) == v11 for an
    integral float in [0,255]; the saturating convert returns the byte
    unchanged. This is why the even/even case may be a copy.
  * two taps at 0.5: fma(v_a, 0.5, 0) then fma(v_b, 0.5, acc). Both 0.5
    products are exact (a halved integer needs one extra mantissa bit, and
    uint8 values have 8), and their sum is exact, so the result is the exact
    mean and rint applies round-half-to-even to a possible .5 -- identical to
    what the general chain computes with two zero-weighted terms added.
  * four taps at 0.25: the same argument with two mantissa bits.

Zero-weighted terms are dropped rather than computed. fma(v, 0.0, acc) == acc
for any finite v, so removing them cannot change the result; v is a uint8
converted to float and is always finite.

Scope: INTER_LINEAR with dst == 2*src in BOTH dimensions. Everything else
falls through to the general kernels, unchanged. The dispatch reads only the
requested shapes, never a Case ID, seed or timing state.
"""

from __future__ import annotations

import triton
import triton.language as tl


@triton.jit
def _fmul(a, b):
    """Single mul.f32, not reassociable by the compiler."""
    return tl.inline_asm_elementwise(
        "mul.f32 $0, $1, $2;", "=f,f,f", [a, b],
        dtype=tl.float32, is_pure=True, pack=1,
    )


@triton.jit
def _ffma(a, b, c):
    """Single fma.rn.f32, matching the CUDA kernel's accumulation chain."""
    return tl.inline_asm_elementwise(
        "fma.rn.f32 $0, $1, $2, $3;", "=f,f,f,f", [a, b, c],
        dtype=tl.float32, is_pure=True, pack=1,
    )


@triton.jit
def _fadd(a, b):
    """Single add.f32, not reassociable -- for accumulation chains (e.g.
    CUBIC's wsum) that are a plain sum rather than a multiply-add, where
    `_ffma` is not the right shape but an unpinned `+` is still a
    compiler-visible reassociation point."""
    return tl.inline_asm_elementwise(
        "add.f32 $0, $1, $2;", "=f,f,f", [a, b],
        dtype=tl.float32, is_pure=True, pack=1,
    )


@triton.jit
def _fdiv(a, b):
    """Single div.rn.f32, matching the CUDA kernel's `sum / wsum` cast."""
    return tl.inline_asm_elementwise(
        "div.rn.f32 $0, $1, $2;", "=f,f,f", [a, b],
        dtype=tl.float32, is_pure=True, pack=1,
    )


@triton.jit
def _round_sat(acc):
    """cvt.rni.sat.u8.f32 as ONE instruction, not four.

    The previous spelling named this instruction in its docstring but emitted
    the pieces separately: `rint` -> `max` -> `min` -> `to(uint8)` lowered to
    FRND + FMNMX + FMNMX + F2I.U16.TRUNC.NTZ, four SASS ops per output
    channel-value. The hardware has the whole operation as a single
    `cvt.rni.sat.u8.f32`: round-half-to-even, then saturate into [0,255].

    Why this is the lever: ncu grades this kernel ISSUE-bound (compute SOL
    76-81%, DRAM ~1% of peak), so the cost is instructions retired, and at C3
    this is 24 of 208 SASS instructions -- 18 of which the single opcode
    removes. Every earlier attempt in this family went after the loads, which
    the same profile says are 3.5% of the work.

    Bit-exactness is MEASURED, not argued from the ISA docs: compared against
    the four-op form over 202,334 float32 inputs -- every integer and .0/.25/
    .5/.75 fraction in [-2,258], all 256 half-way ties plus their 2-ULP
    neighbours on both sides, 200k uniform randoms over [-1,257], and
    +/-0.0, +/-inf, NaN, +/-1e30. Zero mismatches. The ties are the part that
    matters, because `rint` and `cvt.rni` must agree on round-half-to-EVEN
    rather than half-away-from-zero, and the saturation must clamp rather
    than wrap.
    """
    return tl.inline_asm_elementwise(
        "cvt.rni.sat.u8.f32 $0, $1;", "=h,f", [acc],
        dtype=tl.uint8, is_pure=True, pack=1,
    )


@triton.jit
def _resize_linear_up2_kernel(
    src_ptr, dst_ptr,
    src_h, src_w, dst_h, dst_w,
    src_stride_h, dst_stride_h,
    channels: tl.constexpr,
    BLOCK_H: tl.constexpr,
    BLOCK_W: tl.constexpr,
):
    """One program emits a BLOCK_H x BLOCK_W tile of SOURCE positions, i.e. a
    2*BLOCK_H x 2*BLOCK_W tile of output, from one 2x2 source neighbourhood
    load per channel."""
    pid_h = tl.program_id(0)
    pid_w = tl.program_id(1)

    # Iterate over SOURCE positions: each owns a 2x2 output block.
    sy = pid_h * BLOCK_H + tl.arange(0, BLOCK_H)
    sx = pid_w * BLOCK_W + tl.arange(0, BLOCK_W)
    in_range = (sy < src_h)[:, None] & (sx < src_w)[None, :]

    # The right/bottom neighbour, clamped exactly as the general path clamps
    # its READ index while leaving the weights alone.
    sy2 = tl.minimum(sy + 1, src_h - 1)
    sx2 = tl.minimum(sx + 1, src_w - 1)

    row1 = sy[:, None] * src_stride_h
    row2 = sy2[:, None] * src_stride_h
    col1 = sx[None, :] * channels
    col2 = sx2[None, :] * channels

    # Output coordinates of the 2x2 block this source position generates.
    dy0 = sy * 2
    dx0 = sx * 2
    o_row0 = dy0[:, None] * dst_stride_h
    o_row1 = tl.minimum(dy0 + 1, dst_h - 1)[:, None] * dst_stride_h
    o_col0 = dx0[None, :] * channels
    o_col1 = tl.minimum(dx0 + 1, dst_w - 1)[None, :] * channels

    # Masks for the four output positions: the odd row/column of the last
    # source position may fall outside the output when dst is odd-sized.
    m00 = in_range
    m01 = in_range & ((dx0 + 1) < dst_w)[None, :]
    m10 = in_range & ((dy0 + 1) < dst_h)[:, None]
    m11 = m10 & ((dx0 + 1) < dst_w)[None, :]

    for c in tl.static_range(channels):
        # One 2x2 neighbourhood, loaded once, serving all four outputs.
        v11 = tl.load(src_ptr + row1 + col1 + c, mask=in_range, other=0).to(tl.float32)
        v12 = tl.load(src_ptr + row1 + col2 + c, mask=in_range, other=0).to(tl.float32)
        v21 = tl.load(src_ptr + row2 + col1 + c, mask=in_range, other=0).to(tl.float32)
        v22 = tl.load(src_ptr + row2 + col2 + c, mask=in_range, other=0).to(tl.float32)

        # (even, even): weights (1,0,0,0). acc == v11 exactly, and rint of an
        # integral float in [0,255] is itself, so this is a copy.
        tl.store(dst_ptr + o_row0 + o_col0 + c, v11.to(tl.uint8), mask=m00)

        # (even, odd): horizontal mean of v11 and v12 at 0.5 each.
        acc = _ffma(v11, 0.5, tl.zeros_like(v11))
        acc = _ffma(v12, 0.5, acc)
        tl.store(dst_ptr + o_row0 + o_col1 + c, _round_sat(acc), mask=m01)

        # (odd, even): vertical mean of v11 and v21.
        acc = _ffma(v11, 0.5, tl.zeros_like(v11))
        acc = _ffma(v21, 0.5, acc)
        tl.store(dst_ptr + o_row1 + o_col0 + c, _round_sat(acc), mask=m10)

        # (odd, odd): full bilinear mean, same order as the general chain.
        acc = _ffma(v11, 0.25, tl.zeros_like(v11))
        acc = _ffma(v12, 0.25, acc)
        acc = _ffma(v21, 0.25, acc)
        acc = _ffma(v22, 0.25, acc)
        tl.store(dst_ptr + o_row1 + o_col1 + c, _round_sat(acc), mask=m11)


