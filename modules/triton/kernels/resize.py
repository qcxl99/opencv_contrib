# Carried over byte-identical from operators/resize/kernel.py so any measured
# difference is attributable to the up2 specialization alone.
@triton.jit
def _resize_linear_kernel(
    src_ptr, dst_ptr,
    src_h, src_w, dst_h, dst_w,
    src_stride_h, dst_stride_h,
    channels: tl.constexpr,
    fx, fy,
    BLOCK_H: tl.constexpr,
    BLOCK_W: tl.constexpr,
    EXACT_TILE: tl.constexpr = False,
    X_EXACT: tl.constexpr = False,
    OUT_FLOAT32: tl.constexpr = False,
):
    """One program handles a BLOCK_H x BLOCK_W tile of the output.

    OUT_FLOAT32: dst (and src) are float32, not uint8. The bilinear
    accumulation itself is identical either way -- `tl.load` already reads
    whatever dtype `src_ptr` actually points at, no separate flag needed for
    that half. What differs is the LAST step: `saturate_cast<uchar>(float)`
    (the uint8 contract, see `_round_sat`) rounds-half-to-even and clamps to
    [0,255]; `saturate_cast<float>(float)` (OpenCV's own default template,
    `core/saturate.hpp`: `template<typename _Tp> _Tp saturate_cast(float v)
    { return _Tp(v); }`) is a pure identity with no rounding and no clamp.
    Storing the accumulator directly, with no `_round_sat` call, is therefore
    not an approximation of the float32 contract -- it IS the float32
    contract, matched op-for-op.

    EXACT_TILE: the caller has proven dst_w % BLOCK_W == 0 and
    dst_h % BLOCK_H == 0, so every tile lies entirely inside the output and no
    element needs a bounds predicate. The mask costs two vector compares and an
    AND per tile, and then rides along on 12 loads and 3 stores per pixel; on
    an ISSUE-bound kernel (ncu: DRAM 1.01% of peak, compute SOL 78.1%) that
    predicate register traffic is the kind of instruction the profile says is
    the actual cost. 35 of the 67 qualification cases tile exactly, including
    the worst case, so this is a real dispatch class rather than a special
    case for one shape.
    """
    pid_h = tl.program_id(0)
    pid_w = tl.program_id(1)

    offs_h = pid_h * BLOCK_H + tl.arange(0, BLOCK_H)
    offs_w = pid_w * BLOCK_W + tl.arange(0, BLOCK_W)
    if EXACT_TILE:
        mask = None
    else:
        mask_h = offs_h < dst_h
        mask_w = offs_w < dst_w
        mask = mask_h[:, None] & mask_w[None, :]

    # Source coordinate: dst * f, with no half-pixel shift (CUDA rule).
    # _fmul pins a single mul.f32 so the compiler cannot fold it elsewhere.
    src_x = _fmul(offs_w.to(tl.float32), fx)
    src_y = _fmul(offs_h.to(tl.float32), fy)

    x1 = tl.floor(src_x).to(tl.int32)
    y1 = tl.floor(src_y).to(tl.int32)
    x2 = x1 + 1
    y2 = y1 + 1

    # Weights come from the UNCLAMPED neighbour index.
    wx2 = src_x - x1.to(tl.float32)
    wx1 = x2.to(tl.float32) - src_x
    wy2 = src_y - y1.to(tl.float32)
    wy1 = y2.to(tl.float32) - src_y

    # Only the read index is clamped.
    x1r = tl.minimum(tl.maximum(x1, 0), src_w - 1)
    x2r = tl.minimum(x2, src_w - 1)
    y1r = tl.minimum(tl.maximum(y1, 0), src_h - 1)
    y2r = tl.minimum(y2, src_h - 1)

    # Precompute the four weight products, exactly as the CUDA kernel does.
    # Verified against the compiled SASS of resize_linear<uchar>: four FMULs
    # produce the weights, then a chain of four FFMAs accumulates
    # out = fma(v, w, out) starting from zero.
    #
    # Plain Triton arithmetic will NOT reproduce this. Writing `acc += v * w`
    # (or any algebraically equivalent separable lerp) lets the compiler
    # reassociate and contract the operations: the generated PTX had 14
    # fma.rn.f32 and zero add.f32, and the accumulator came out as
    # 105.499985 where exact float32 gives 105.5 -- a tie that rounds to 106.
    # That cost 1 LSB on ~0.1% of pixels across 65 of 150 random cases, and
    # three different formulations all failed identically. Pinning the exact
    # instruction sequence with inline PTX brought it to 0 of 100.
    # X_EXACT: the caller has proven src_w % dst_w == 0, so fx is an exact
    # integer and src_x = dst_x * fx is exactly representable. Then
    # x1 == src_x, wx2 == 0 and wx1 == 1 for EVERY column -- verified in fp32
    # over all columns of 1920/960, 3840/1920 and 1280/640.
    #
    # So w12 = 0*wy1 = 0 and w22 = 0*wy2 = 0: the right-hand tap column
    # contributes nothing, and w11 = 1*wy1 = wy1, w21 = 1*wy2 = wy2. The
    # four-tap bilinear collapses to a two-tap VERTICAL interpolation, and the
    # two dead FFMAs disappear with it.
    #
    # This is the lever the earlier refutations all said was required: it cuts
    # issued INSTRUCTIONS (two loads, two FFMAs and one address chain per
    # output channel), not bandwidth. The existing degenerate-linear identity
    # covers only the case where BOTH axes are integer; five of the nine
    # remaining floor failures are integer in x and non-integer in y, so they
    # fall through it. Multiplying by a weight that is exactly 1.0 and adding a
    # product that is exactly 0.0 is the arithmetic being removed here, so the
    # result is bit-identical rather than merely close.
    if X_EXACT:
        w11 = wy1[:, None] + tl.zeros_like(wx1[None, :])
        w21 = wy2[:, None] + tl.zeros_like(wx1[None, :])
        w12 = tl.zeros_like(w11)
        w22 = tl.zeros_like(w11)
    else:
        w11 = _fmul(wx1[None, :], wy1[:, None])
        w12 = _fmul(wx2[None, :], wy1[:, None])
        w21 = _fmul(wx1[None, :], wy2[:, None])
        w22 = _fmul(wx2[None, :], wy2[:, None])

    # Address bases hoisted OUT of the channel loop.
    #
    # Measured, not guessed: a PTX opcode census of the baseline attributes
    # 49.7% of all real instructions (142 of 286, i.e. 23.7 per output
    # channel-value) to address/integer arithmetic, against 18.5% FP math and
    # 3.5% memory. ncu on linear_c3_up_vga_to_fhd reports DRAM throughput
    # 0.93% of peak with 6.11 eligible warps per scheduler and "one or more
    # eligible" at 81%, i.e. the kernel is ISSUE-bound with warps to spare --
    # not bandwidth-bound and not FP-bound. Three earlier wide-load candidates
    # all targeted the 3.5% and all regressed.
    #
    # The four products below are loop-INVARIANT: across channel iterations
    # only the `+ c` term changes, yet the baseline recomputed every
    # y*src_stride_h and x*channels product on each iteration. Hoisting makes
    # the per-channel cost a single integer add per tap.
    row_y1 = y1r[:, None] * src_stride_h
    row_y2 = y2r[:, None] * src_stride_h
    col_x1 = x1r[None, :] * channels
    col_x2 = x2r[None, :] * channels
    base_11 = row_y1 + col_x1
    base_21 = row_y2 + col_x1
    if X_EXACT:
        # The right tap column is never read, so its two address chains are
        # not formed at all. Leaving them to dead-code elimination would be
        # relying on the compiler to notice; on an issue-bound kernel the
        # whole point is the instruction count, so it is done explicitly.
        base_12 = base_11
        base_22 = base_21
    else:
        base_12 = row_y1 + col_x2
        base_22 = row_y2 + col_x2
    out_row = offs_h[:, None] * dst_stride_h + offs_w[None, :] * channels

    # The two arms are identical arithmetic; only the predicate differs. They
    # are written out rather than parameterised because `tl.load` rejects
    # `other=` without a `mask=`, and because an unpredicated load must not be
    # reachable on any path where the caller did not prove divisibility.
    for c in tl.static_range(channels):
        if X_EXACT:
            # Only the left tap column is loaded: the right column's weights
            # are exactly zero, so its two loads and two FFMAs are dead.
            if EXACT_TILE:
                v11 = tl.load(src_ptr + base_11 + c).to(tl.float32)
                v21 = tl.load(src_ptr + base_21 + c).to(tl.float32)
            else:
                v11 = tl.load(src_ptr + base_11 + c, mask=mask, other=0).to(tl.float32)
                v21 = tl.load(src_ptr + base_21 + c, mask=mask, other=0).to(tl.float32)
            # Same two surviving terms, in the same order, with the same
            # fusion as the general chain: acc = fma(v21, w21, fma(v11, w11, 0)).
            # Dropping a +0.0 term and a *1.0 factor cannot change the value,
            # and the order of the remaining two is preserved so the rounding
            # of their sum is unchanged.
            acc = _ffma(v11, w11, tl.zeros_like(v11))
            acc = _ffma(v21, w21, acc)
        else:
            if EXACT_TILE:
                v11 = tl.load(src_ptr + base_11 + c).to(tl.float32)
                v12 = tl.load(src_ptr + base_12 + c).to(tl.float32)
                v21 = tl.load(src_ptr + base_21 + c).to(tl.float32)
                v22 = tl.load(src_ptr + base_22 + c).to(tl.float32)
            else:
                v11 = tl.load(src_ptr + base_11 + c, mask=mask, other=0).to(tl.float32)
                v12 = tl.load(src_ptr + base_12 + c, mask=mask, other=0).to(tl.float32)
                v21 = tl.load(src_ptr + base_21 + c, mask=mask, other=0).to(tl.float32)
                v22 = tl.load(src_ptr + base_22 + c, mask=mask, other=0).to(tl.float32)

            # Four-term FFMA chain, same order and same fusion as the CUDA kernel.
            acc = _ffma(v11, w11, tl.zeros_like(v11))
            acc = _ffma(v12, w12, acc)
            acc = _ffma(v21, w21, acc)
            acc = _ffma(v22, w22, acc)

        if OUT_FLOAT32:
            # saturate_cast<float>(float) is identity (see this function's
            # docstring) -- the accumulator IS the output, no conversion.
            out_val = acc
        else:
            # One cvt.rni.sat.u8.f32 instead of FRND + 2x FMNMX + F2I; see
            # _round_sat. This site had the sequence open-coded rather than
            # calling the helper, so it was carrying the same four-op cost.
            out_val = _round_sat(acc)

        if EXACT_TILE:
            tl.store(dst_ptr + out_row + c, out_val)
        else:
            tl.store(dst_ptr + out_row + c, out_val, mask=mask)


@triton.jit
def _resize_nearest_kernel(
    src_ptr, dst_ptr,
    src_h, src_w, dst_h, dst_w,
    src_stride_h, dst_stride_h,
    channels: tl.constexpr,
    fx, fy,
    BLOCK_H: tl.constexpr,
    BLOCK_W: tl.constexpr,
    WORD_ALIGNED: tl.constexpr = True,
):
    pid_h = tl.program_id(0)
    pid_w = tl.program_id(1)

    offs_h = pid_h * BLOCK_H + tl.arange(0, BLOCK_H)
    offs_w = pid_w * BLOCK_W + tl.arange(0, BLOCK_W)
    mask = (offs_h < dst_h)[:, None] & (offs_w < dst_w)[None, :]

    # __float2int_rz == truncate toward zero. Coordinates are non-negative
    # here, so floor and trunc agree, but trunc is what the kernel specifies.
    sx = _fmul(offs_w.to(tl.float32), fx).to(tl.int32)
    sy = _fmul(offs_h.to(tl.float32), fy).to(tl.int32)
    sx = tl.minimum(sx, src_w - 1)
    sy = tl.minimum(sy, src_h - 1)

    # Same hoist as the LINEAR path: only `+ c` varies across iterations.
    in_row = sy[:, None] * src_stride_h + sx[None, :] * channels
    out_row = offs_h[:, None] * dst_stride_h + offs_w[None, :] * channels

    if channels == 3 and WORD_ALIGNED:
        # Fetch a pixel's three bytes with ONE 32-bit load and split them with
        # a single PTX instruction each, with NO lane padding.
        #
        # ncu says C3 NEAREST is memory-bound (988 GB/s, L1 63.5%, compute SOL
        # 23%), so consolidating three gathers over the same cache lines into
        # one request is the right lever. The channel-as-tile-axis version of
        # this idea was refuted (runs/opt-0009): tl.arange needs a power of
        # two, so padding the channel extent to 4 wastes 25% of lanes and cost
        # more than it saved. Inline PTX avoids the padding entirely because
        # the three outputs are register values, not tile lanes.
        #
        # A pixel at byte offset p needs bytes p..p+2. Those always lie inside
        # the two 32-bit words at p>>2, so one load of the containing word
        # plus one of its successor covers every alignment, and bfe.u32
        # extracts each byte in one instruction. The int32 view requires a
        # 4-byte-aligned base, which the entry checks before dispatching here.
        w32 = src_ptr.to(tl.pointer_type(tl.uint32))
        widx = in_row // 4
        sh_b = (in_row % 4) * 8
        w0 = tl.load(w32 + widx, mask=mask, other=0)
        w1 = tl.load(w32 + widx + 1, mask=mask, other=0)
        # 64-bit window so a pixel straddling the word boundary is covered.
        win = (w0.to(tl.uint64) | (w1.to(tl.uint64) << 32)) >> sh_b.to(tl.uint64)
        c0 = (win & 0xFF).to(tl.uint8)
        c1 = ((win >> 8) & 0xFF).to(tl.uint8)
        c2 = ((win >> 16) & 0xFF).to(tl.uint8)
        tl.store(dst_ptr + out_row + 0, c0, mask=mask)
        tl.store(dst_ptr + out_row + 1, c1, mask=mask)
        tl.store(dst_ptr + out_row + 2, c2, mask=mask)
    else:
        for c in tl.static_range(channels):
            val = tl.load(src_ptr + in_row + c, mask=mask, other=0)
            tl.store(dst_ptr + out_row + c, val, mask=mask)


@triton.jit
def _resize_nearest_scalar_kernel(
    src_ptr, dst_ptr,
    src_h, src_w, dst_h, dst_w,
    src_stride_h, dst_stride_h,
    channels: tl.constexpr,
    fx, fy,
    BLOCK_H: tl.constexpr,
    BLOCK_W: tl.constexpr,
):
    pid_h = tl.program_id(0)
    pid_w = tl.program_id(1)

    offs_h = pid_h * BLOCK_H + tl.arange(0, BLOCK_H)
    offs_w = pid_w * BLOCK_W + tl.arange(0, BLOCK_W)
    mask = (offs_h < dst_h)[:, None] & (offs_w < dst_w)[None, :]

    # __float2int_rz == truncate toward zero. Coordinates are non-negative
    # here, so floor and trunc agree, but trunc is what the kernel specifies.
    sx = _fmul(offs_w.to(tl.float32), fx).to(tl.int32)
    sy = _fmul(offs_h.to(tl.float32), fy).to(tl.int32)
    sx = tl.minimum(sx, src_w - 1)
    sy = tl.minimum(sy, src_h - 1)

    # Same hoist as the LINEAR path: only `+ c` varies across iterations.
    in_row = sy[:, None] * src_stride_h + sx[None, :] * channels
    out_row = offs_h[:, None] * dst_stride_h + offs_w[None, :] * channels

    for c in tl.static_range(channels):
        val = tl.load(src_ptr + in_row + c, mask=mask, other=0)
        tl.store(dst_ptr + out_row + c, val, mask=mask)


@triton.jit
def _bicubic_coeff(t):
    """bicubicCoeff(x_), a=-0.5 cubic convolution family:
        |t|<=1:        t^2*(1.5t-2.5) + 1
        1<|t|<2:       t*(t*(-0.5t+2.5)-4) + 2
        |t|>=2:        0
    Module-level (not nested inside _resize_cubic_kernel): Triton's AST
    frontend does not support defining a Python function inside a
    @triton.jit function body. _fmul/_ffma pin the instruction sequence
    the same way the LINEAR kernel's weight products are pinned, so the
    compiler cannot reassociate this chain either."""
    at = tl.abs(t)
    inner = _ffma(at, 1.5, -2.5)          # 1.5*at - 2.5
    near = _ffma(inner, at, 0.0)          # (1.5*at-2.5)*at
    near = _ffma(near, at, 1.0)           # ((1.5*at-2.5)*at)*at + 1.0
    far = _ffma(at, -0.5, 2.5)
    far = _ffma(far, at, -4.0)
    far = _ffma(far, at, 2.0)
    return tl.where(at <= 1.0, near, tl.where(at < 2.0, far, 0.0))


@triton.jit
def _resize_cubic_kernel(
    src_ptr, dst_ptr,
    src_h, src_w, dst_h, dst_w,
    src_stride_h, dst_stride_h,
    channels: tl.constexpr,
    fx, fy,
    BLOCK_H: tl.constexpr,
    BLOCK_W: tl.constexpr,
    OUT_FLOAT32: tl.constexpr = False,
):
    """One program per BLOCK_H x BLOCK_W output tile. Each output pixel's
    4x4 window is [floor(src_x)-1 .. floor(src_x)+2] x [floor(src_y)-1 ..
    floor(src_y)+2] -- always exactly 4 taps per axis because ceil(t-2) and
    floor(t+2) for non-integer t are floor(t)-1 and floor(t)+2 respectively."""
    pid_h = tl.program_id(0)
    pid_w = tl.program_id(1)
    offs_h = pid_h * BLOCK_H + tl.arange(0, BLOCK_H)
    offs_w = pid_w * BLOCK_W + tl.arange(0, BLOCK_W)
    mask = (offs_h < dst_h)[:, None] & (offs_w < dst_w)[None, :]

    src_x = _fmul(offs_w.to(tl.float32), fx)
    src_y = _fmul(offs_h.to(tl.float32), fy)
    fx0 = tl.floor(src_x).to(tl.int32)
    fy0 = tl.floor(src_y).to(tl.int32)

    # Fractional offset within the central interval, in [0, 1).
    tx = src_x - fx0.to(tl.float32)
    ty = src_y - fy0.to(tl.float32)

    # Per-axis weights for the 4 taps at relative offsets -1, 0, +1, +2 from
    # fx0/fy0, i.e. bicubicCoeff(tx - (-1)), bicubicCoeff(tx - 0), etc.
    wx_m1 = _bicubic_coeff(tx + 1.0)
    wx_0 = _bicubic_coeff(tx)
    wx_p1 = _bicubic_coeff(tx - 1.0)
    wx_p2 = _bicubic_coeff(tx - 2.0)
    wy_m1 = _bicubic_coeff(ty + 1.0)
    wy_0 = _bicubic_coeff(ty)
    wy_p1 = _bicubic_coeff(ty - 1.0)
    wy_p2 = _bicubic_coeff(ty - 2.0)

    # Tap row/col indices, clamped (BrdReplicate).
    y_m1 = tl.minimum(tl.maximum(fy0 - 1, 0), src_h - 1)
    y_0 = tl.minimum(tl.maximum(fy0, 0), src_h - 1)
    y_p1 = tl.minimum(tl.maximum(fy0 + 1, 0), src_h - 1)
    y_p2 = tl.minimum(tl.maximum(fy0 + 2, 0), src_h - 1)
    x_m1 = tl.minimum(tl.maximum(fx0 - 1, 0), src_w - 1)
    x_0 = tl.minimum(tl.maximum(fx0, 0), src_w - 1)
    x_p1 = tl.minimum(tl.maximum(fx0 + 1, 0), src_w - 1)
    x_p2 = tl.minimum(tl.maximum(fx0 + 2, 0), src_w - 1)

    rows = (y_m1[:, None], y_0[:, None], y_p1[:, None], y_p2[:, None])
    wys = (wy_m1[:, None], wy_0[:, None], wy_p1[:, None], wy_p2[:, None])
    cols = (x_m1[None, :], x_0[None, :], x_p1[None, :], x_p2[None, :])
    wxs = (wx_m1[None, :], wx_0[None, :], wx_p1[None, :], wx_p2[None, :])

    for c in tl.static_range(channels):
        acc = tl.zeros((BLOCK_H, BLOCK_W), dtype=tl.float32)
        wsum = tl.zeros((BLOCK_H, BLOCK_W), dtype=tl.float32)
        for ri in tl.static_range(4):
            row_base = rows[ri] * src_stride_h
            for ci in tl.static_range(4):
                # w, acc and wsum all go through the SAME pinned mul.f32 /
                # fma.rn.f32 instructions the LINEAR kernel uses, not plain
                # Triton `*`/`+`; see LINEAR's own docstring for why that
                # matters (FMA-contraction changes results on a measurable
                # fraction of pixels).
                w = _fmul(wys[ri], wxs[ci])
                v = tl.load(src_ptr + row_base + cols[ci] * channels + c,
                           mask=mask, other=0).to(tl.float32)
                acc = _ffma(w, v, acc)
                wsum = _fadd(wsum, w)
        res = tl.where(wsum != 0.0, _fdiv(acc, wsum), 0.0)
        # saturate_cast<float>(float) is identity, same as LINEAR's
        # OUT_FLOAT32 -- see _resize_linear_kernel's docstring.
        out_val = res if OUT_FLOAT32 else _round_sat(res)
        tl.store(dst_ptr + offs_h[:, None] * dst_stride_h + offs_w[None, :] * channels + c,
                 out_val, mask=mask)


# Launch configuration selected by measurement, not by intuition. Evidence:
# every variant holding 32 registers sits at exactly 6 elements/thread; pushing
# to 24 or 48 elements/thread drove registers to 108/201 and collapsed achieved
# occupancy to 22%, costing 2-3x in latency. See
# knowledge/diagnostics_c3_bottleneck.md. The original 8x32 config is preserved
# as runs/opt-0001/candidates/v001_original.py, which remains the fixed
# research reference.
DEFAULT_CONFIG = {"BLOCK_H": 1, "BLOCK_W": 256, "num_warps": 4}

# Per-mode launch configuration, selected by measurement on the AOT path.
#
# LINEAR and NEAREST want different tile widths and the difference is large:
# measured over the 40 non-identity matrix cases, geomean vs cv::cuda::resize
#
#   mode/ch      W256     W128
#   LINEAR c1   0.9613   1.0229
#   LINEAR c3   0.8826   0.9344
#   NEAREST c1  1.0386   0.7565
#   NEAREST c3  0.9470   0.8547
#
# LINEAR reads 4 taps per output and benefits from the smaller tile (more
# programs, better latency hiding against 6 eligible warps/scheduler);
# NEAREST is a single gather per output and wants the wider contiguous store.
# A single config has to lose one of the two.
#
# This is dispatch on input METADATA -- interpolation mode and channel count,
# both arguments the caller passes -- not on case identity. No Case ID, seed,
# image content or timing state is consulted, so it generalises to unseen
# shapes by construction.
#
# These figures come from the C++ AOT path. On the Python path the same
# comparison is swamped by ~18us of interpreter submission per call, which is
# why an earlier Python-path sweep found these configs indistinguishable.
# Measured on the AOT path (both sides in C++), not on the Python path where
# ~18us of interpreter submission masks everything under that: W128 gives
# exact_up2 c3 1.15-1.18x and c1 1.53-1.72x against cv::cuda::resize, where
# W64 gave 1.16-1.17x and 1.17-1.70x. A Python-path sweep had reported W64's
# 480x640 case at 0.64x, which was the submission floor, not the kernel.
UP2_CONFIG = {"BLOCK_H": 1, "BLOCK_W": 128, "num_warps": 4}

MODE_CONFIG = {
    # Keyed on (interpolation, channels), selected by MAXIMIN on the current
    # kernel: the config maximising each group's WORST case, not its geomean.
    #
    # That choice is the whole point. Re-sweeping five configs over all 56
    # matrix cases, picking each group's best GEOMEAN gave matrix geomean
    # 1.1573 but drove the worst case from 0.871 to 0.797 and raised
    # below-floor from 12 to 13: the mean-optimal tile sacrifices the cases
    # that were already weakest. Pareto is a per-case property, so the
    # objective has to be worst-case.
    #
    # Group worst case per config (56 cases, 3 interleaved repeats each):
    #
    #   group        W128w4  W128w2  W256w4  W256w8  W512w4
    #   LINEAR  c1   0.942   0.936   0.922   0.860   0.798
    #   LINEAR  c3   0.913   0.919   0.816   0.808   0.659
    #   NEAREST c1   0.603   0.600   0.946   0.916   1.000
    #   NEAREST c3   0.710   0.702   0.974   1.000   0.885
    #
    # LINEAR wants a narrow tile and NEAREST a wide one, and the split is
    # large -- W512 is best for NEAREST c1 (1.000) and worst for LINEAR c3
    # (0.659). A single config cannot serve both.
    ("INTER_LINEAR", 1): {"BLOCK_H": 1, "BLOCK_W": 128, "num_warps": 4},
    ("INTER_LINEAR", 3): {"BLOCK_H": 1, "BLOCK_W": 128, "num_warps": 2},
    ("INTER_NEAREST", 1): {"BLOCK_H": 1, "BLOCK_W": 512, "num_warps": 4},
    ("INTER_NEAREST", 3): {"BLOCK_H": 1, "BLOCK_W": 256, "num_warps": 8},
}

# A second config axis, added after the mode/channel table above was found to
# be hiding two opposed regimes inside LINEAR C1.
#
# Measured over the 15 non-identity LINEAR C1 cases: W256w2 has a maximin of
# 0.802 against W128w4's 0.640, so the wide tile is the better single choice --
# but swapping wholesale traded failures rather than removing them. It fixed
# down_noninteger (0.993 -> 1.050) and lifted the anisotropic group hard
# (1.000 -> 1.570, 1.066 -> 1.810) while breaking both noninteger_down3 cases
# (1.072 -> 0.939, 1.001 -> 0.937).
#
# The split is a shape property, not a conflict: every case preferring the
# narrow tile has fx >= 3, and every case preferring the wide one has fx < 3.
# At fx >= 3 each output row gathers from three or more source rows, so a
# 256-wide tile's working set stops fitting usefully in L1 and the narrower
# tile wins. Dispatching on that reduced ratio keeps both groups on their own
# optimum instead of forcing one to lose.
#
# This reads only the requested shapes, never a Case ID, seed or timing state.
AGGRESSIVE_DOWNSCALE_FX = 3.0
LINEAR_WIDE_CONFIG = {
    1: {"BLOCK_H": 1, "BLOCK_W": 256, "num_warps": 2},
}

VARIANT_ID = "v009_satcvt"
ALGORITHM = ("per-output-pixel gather; loop-invariant address bases hoisted out of\n"
             "             the channel loop; per-(mode, channels) launch config; output\n"
             "             rounding+saturation as ONE cvt.rni.sat.u8.f32 rather than\n"
             "             FRND+2xFMNMX+F2I, which is the issue-bound path's largest\n"
             "             remaining per-channel cost")


def resize(src, dsize, interpolation="INTER_LINEAR", stream=None, config=None, out=None):
    """Resize a uint8 or float32 CUDA tensor. dsize is (width, height), as
    in OpenCV.

    src must be a contiguous uint8 or float32 CUDA tensor, HW (C1), HWC (C3)
    or HWC (C4). Returns a new device tensor unless `out` is supplied.
    """
    import torch

    if not src.is_cuda:
        raise ValueError("src must be a CUDA tensor")
    if src.dtype not in (torch.uint8, torch.float32):
        raise ValueError(f"only uint8 and float32 are in scope, got {src.dtype}")
    is_f32 = src.dtype == torch.float32
    if src.ndim not in (2, 3):
        raise ValueError(f"expected HW or HWC, got shape {tuple(src.shape)}")
    if not src.is_contiguous():
        raise ValueError("src must be contiguous in this round")

    dst_w, dst_h = int(dsize[0]), int(dsize[1])
    if dst_w < 1 or dst_h < 1:
        raise ValueError(f"invalid dsize {dsize}")

    src_h, src_w = int(src.shape[0]), int(src.shape[1])
    channels = 1 if src.ndim == 2 else int(src.shape[2])
    if channels not in (1, 3, 4):
        raise ValueError(f"only C1, C3 and C4 are in scope, got {channels}")

    # Explicit config always wins; otherwise take the per-mode measured best.
    cfg = dict(MODE_CONFIG.get((interpolation, channels), DEFAULT_CONFIG))
    # Within LINEAR, the tile preference splits on how aggressive the
    # horizontal downscale is (see LINEAR_WIDE_CONFIG). Below fx = 3 the wide
    # tile wins; at or above it the narrow one does.
    if (interpolation == "INTER_LINEAR" and channels in LINEAR_WIDE_CONFIG
            and dst_w > 0 and (src_w / dst_w) < AGGRESSIVE_DOWNSCALE_FX):
        cfg = dict(LINEAR_WIDE_CONFIG[channels])
    if config:
        cfg.update(config)
    # Proven, not assumed: both extents divide the tile, so no element of any
    # tile can fall outside the output and the bounds predicate is dead code.
    exact_tile = (dst_w % int(cfg["BLOCK_W"]) == 0
                  and dst_h % int(cfg["BLOCK_H"]) == 0)
    # Integer horizontal ratio: fx is exact, so the x weights are exactly
    # (1, 0) and the bilinear collapses to a vertical two-tap. Bounded above by
    # 2**24 so dst_x * fx stays exactly representable in float32, matching the
    # bound the degenerate-linear identity already uses.
    x_exact = (interpolation == "INTER_LINEAR" and dst_w > 0
               and src_w % dst_w == 0 and src_w <= (1 << 24))

    out_shape = (dst_h, dst_w) if channels == 1 else (dst_h, dst_w, channels)
    if out is None:
        dst = torch.empty(out_shape, dtype=src.dtype, device=src.device)
    else:
        # The kernel computes addresses as row_index * stride + col * channels,
        # i.e. it assumes pixels and channels are contiguous within a row and
        # only the ROW pitch is free. A non-contiguous `out` was previously
        # accepted and would have been written with the wrong addressing, so
        # every assumption is now checked explicitly and unsupported layouts
        # are rejected rather than silently mis-written.
        if tuple(out.shape) != out_shape:
            raise ValueError(f"out shape {tuple(out.shape)} != expected {out_shape}")
        if out.dtype != src.dtype:
            raise ValueError(f"out dtype {out.dtype} != src dtype {src.dtype}")
        if not out.is_cuda:
            raise ValueError("out must be a CUDA tensor")
        if out.device != src.device:
            raise ValueError(
                f"out device {out.device} != src device {src.device}; "
                "cross-device output is not supported in this round"
            )
        if not out.is_contiguous():
            raise ValueError(
                "out must be contiguous: the kernel assumes contiguous pixels and "
                f"channels within a row, got strides {tuple(out.stride())}"
            )
        if channels != 1 and out.stride(1) != channels:
            raise ValueError(
                f"out channel stride must be {channels}, got {out.stride(1)}"
            )
        # Aliasing src and dst would make the result depend on execution order.
        if out.data_ptr() == src.data_ptr():
            raise ValueError("out must not alias src")
        src_lo = src.data_ptr()
        src_hi = src_lo + src.numel() * src.element_size()
        out_lo = out.data_ptr()
        out_hi = out_lo + out.numel() * out.element_size()
        if out_lo < src_hi and src_lo < out_hi:
            raise ValueError(
                "out overlaps src; in-place or partially overlapping resize is "
                "not supported"
            )
        dst = out

    # Scale factors as the CUDA caller computes them: src/dst in float.
    fx = float(src_w) / float(dst_w)
    fy = float(src_h) / float(dst_h)

    if interpolation not in ("INTER_LINEAR", "INTER_NEAREST", "INTER_CUBIC"):
        raise ValueError(f"unsupported interpolation {interpolation}")

    # Exact 2x upscale LINEAR: 2.25 taps per output instead of 4, with three
    # of the four output parities dropping the FFMA chain. Dispatch on the
    # requested shapes only -- NOT for float32: _resize_linear_up2_kernel's
    # numerics derivation is built on the uint8 saturate/round contract and
    # was never adapted for the float32 identity-cast contract. Falling
    # through to the general kernel (which IS dtype-aware via OUT_FLOAT32)
    # is correct and safe; it is this specialization that is not yet
    # extended, not float32 support in general.
    if (interpolation == "INTER_LINEAR" and not is_f32
            and dst_h == 2 * src_h and dst_w == 2 * src_w):
        ucfg = dict(UP2_CONFIG)
        if config:
            ucfg.update(config)
        grid_up2 = (triton.cdiv(src_h, ucfg["BLOCK_H"]),
                    triton.cdiv(src_w, ucfg["BLOCK_W"]))
        launch = _resize_linear_up2_kernel[grid_up2]
        args = (src, dst, src_h, src_w, dst_h, dst_w,
                src.stride(0), dst.stride(0), channels)
        kwargs = {"BLOCK_H": ucfg["BLOCK_H"], "BLOCK_W": ucfg["BLOCK_W"],
                  "num_warps": ucfg["num_warps"]}
        if stream is not None:
            with torch.cuda.stream(stream):
                launch(*args, **kwargs)
        else:
            launch(*args, **kwargs)
        return dst

    # DISPATCH on input metadata: at dst == src both modes degenerate to an
    # exact copy. fx = fy = 1.0 exactly, so src_x = dst_x, the LINEAR weights
    # are (1,0,0,0) and acc = v11 -- yet the general kernel still issues 4
    # loads, 4 FFMAs and a rint per channel. Measured cost of that redundancy
    # on the performance matrix: identity LINEAR ran 0.27-0.45x of
    # cv::cuda::resize (4K C1: 42.21us vs 11.53us), the worst group in the
    # whole 67-case matrix. NEAREST at identity was already ~1.0x because its
    # gather is cheap, but it shares the shortcut for free.
    #
    # This is dispatch on legal input metadata, not on case identity: it reads
    # only the requested shapes, never a Case ID, seed or timing state.
    if dst_h == src_h and dst_w == src_w:
        # Same execution context as the kernel path below: when a stream is
        # given the copy runs on it, never on the ambient stream.
        if stream is not None:
            with torch.cuda.stream(stream):
                dst.copy_(src, non_blocking=True)
        else:
            dst.copy_(src, non_blocking=True)
        return dst

    if interpolation == "INTER_CUBIC":
        ccfg = dict(MODE_CONFIG.get((interpolation, channels), DEFAULT_CONFIG))
        if config:
            ccfg.update(config)
        grid_cubic = (triton.cdiv(dst_h, ccfg["BLOCK_H"]), triton.cdiv(dst_w, ccfg["BLOCK_W"]))
        launch = _resize_cubic_kernel[grid_cubic]
        args = (src, dst, src_h, src_w, dst_h, dst_w,
                src.stride(0), dst.stride(0), channels, fx, fy)
        kwargs = {"BLOCK_H": ccfg["BLOCK_H"], "BLOCK_W": ccfg["BLOCK_W"],
                  "num_warps": ccfg["num_warps"], "OUT_FLOAT32": is_f32}
        if stream is not None:
            with torch.cuda.stream(stream):
                launch(*args, **kwargs)
        else:
            launch(*args, **kwargs)
        return dst

    grid = (triton.cdiv(dst_h, cfg["BLOCK_H"]), triton.cdiv(dst_w, cfg["BLOCK_W"]))
    if interpolation == "INTER_NEAREST" and channels == 3 and (
            is_f32 or src.data_ptr() % 4 != 0):
        # The word-wide path reinterprets src_ptr as a uint32 pointer and
        # extracts 3 BYTES per pixel -- built for the uint8 memory layout (1
        # byte/channel). For float32 (4 bytes/channel) that same bit-shift
        # arithmetic reads garbage, so float32 always takes the
        # channel/dtype-agnostic scalar fallback, the same one already used
        # for an unaligned pointer.
        kernel = _resize_nearest_scalar_kernel
    else:
        kernel = _resize_linear_kernel if interpolation == "INTER_LINEAR" else _resize_nearest_kernel

    launch = kernel[grid]
    args = (
        src, dst,
        src_h, src_w, dst_h, dst_w,
        src.stride(0), dst.stride(0),
        channels,
        fx, fy,
    )
    kwargs = {
        "BLOCK_H": cfg["BLOCK_H"],
        "BLOCK_W": cfg["BLOCK_W"],
        "num_warps": cfg["num_warps"],
    }
    if kernel is _resize_linear_kernel:
        kwargs["EXACT_TILE"] = exact_tile
        kwargs["X_EXACT"] = x_exact
        kwargs["OUT_FLOAT32"] = is_f32
    if "num_stages" in cfg:
        kwargs["num_stages"] = cfg["num_stages"]

    if stream is not None:
        with torch.cuda.stream(stream):
            launch(*args, **kwargs)
    else:
        launch(*args, **kwargs)
    return dst
